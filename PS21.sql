"""
Show each artist with: 
 Total Sales  
 Percentage Contribution to Overall Sales  

Example: 
| Artist | Sales | Sales % |
"""
SELECT
    ar.name,
    SUM(il.unit_price * il.quantity) AS sales,

    ROUND(
        (
            SUM(il.unit_price * il.quantity) * 100.0
            / SUM(SUM(il.unit_price * il.quantity)) OVER ()
        )::numeric,
        2
    ) AS per_sales

FROM artist ar

JOIN album al
ON ar.artist_id = al.artist_id

JOIN track t
ON al.album_id = t.album_id

JOIN invoice_line il
ON t.track_id = il.track_id

GROUP BY
    ar.artist_id,
    ar.name

ORDER BY sales DESC;

