"""
Show each genre with: 
 Rock Track Count  
 Non-Rock Track Count  
(Use Conditional Aggregation.)
"""
SELECT
    g.name,

    COUNT(
        CASE
            WHEN g.name = 'Rock' THEN t.track_id
        END
    ) AS rock_track_count,

    COUNT(
        CASE
            WHEN g.name <> 'Rock' THEN t.track_id
        END
    ) AS non_rock_track_count

FROM genre g

JOIN track t
ON g.genre_id = t.genre_id

GROUP BY
    g.genre_id,
    g.name;

