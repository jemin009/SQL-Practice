"""
Create a final business report returning: 
 Artist Name  
 Total Albums  
 Total Tracks  
 Total Sales  
 Rank based on Total Sales 
"""
select 
	ar.name,
	count(distinct al.album_id) as total_albums,
	count(distinct t.track_id) as total_tracks,
	sum(il.unit_price * il.quantity) as total_Sales,
	rank() over (order by sum(il.unit_price * il.quantity))
from artist ar

join album al
on ar.artist_id = al.artist_id

join track t
on al.album_id = t.album_id

join invoice_line il
on t.track_id = il.track_id

group by 1
order by 4
