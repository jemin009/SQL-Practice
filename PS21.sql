"""
Show each customer's: 
 First Name  
 Last Name  
 Total Invoices  
 Total Amount Spent 
"""
select 
	c.first_name,
	c.last_name,
	count(i.invoice_id) as total_invoices,
	sum(i.total) as total_amount_spent
from customer c
join invoice i
on c.customer_id = i.customer_id
group by 1,2;

